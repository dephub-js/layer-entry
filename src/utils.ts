import { path } from '@dephub/path';
import { randomLetters } from '@dephub/random-letter';
import { writeFile } from '@dephub/write';

import type { EntryContext, EntryFileName } from '#/core/types.ts';

export function createUniqueAlias(seen: Set<string>): string {
  let alias = randomLetters();
  while (seen.has(alias)) {
    alias = randomLetters();
  }
  seen.add(alias);
  return alias;
}

export function dim(str: string) {
  return `\x1B[2m${str.replace(/\x1b\[22m/g, '\x1B[2m')}\x1B[22m`;
}

export function green(str: string) {
  return `\x1B[32m${str.replace(/\x1b\[39m/g, '\x1B[32m')}\x1B[39m`;
}

export async function writeEntryFile(
  fileName: EntryFileName,
  { outDir, docType, importsMap, name }: EntryContext,
) {
  const targetPath = path.join(outDir, fileName);

  if (fileName === 'package.json') {
    await writeEntryPackage(targetPath, name);
    return;
  }

  const isTypeDef = fileName === 'index.d.ts';
  const typeofKeyword = isTypeDef ? ' typeof' : '';
  const declareKeyword = isTypeDef ? 'declare ' : '';
  const assignmentToken = isTypeDef ? ':' : ' =';

  const importStatements: Array<string> = [];
  const groupBlocks: Array<string> = [];
  const seenAliases = new Set<string>();

  for (const [groupName, groupImports] of Object.entries(importsMap)) {
    const entries: Array<string> = [];

    for (const [importName, modulePath] of Object.entries(groupImports)) {
      const alias = createUniqueAlias(seenAliases);
      const relPath = path.relative(outDir, modulePath).replaceAll('\\', '/');
      const specifier = relPath.startsWith('.') ? relPath : `./${relPath}`;

      entries.push(`'${importName}':${typeofKeyword} ${alias}`);
      importStatements.push(
        `import ${alias} from '${specifier}' with { type: 'json' };`,
      );
    }

    groupBlocks.push(`'${groupName}': {\n    ${entries.join(',\n    ')}\n  }`);
  }

  const content = `${importStatements.join('\n')}\n\nexport ${declareKeyword}const ${docType}${assignmentToken} {\n  ${groupBlocks.join(',\n  ')},\n};\n`;
  await writeFile(targetPath, content);
}

export async function writeEntryPackage(
  filePath: string,
  name: string,
): Promise<void> {
  await writeFile(
    filePath,
    JSON.stringify(
      {
        name: `dot-${name}`,
        type: 'module',
        version: '0.0.0',
        description: `This package is auto-generated by ${name}`,
        types: './index.d.ts',
        main: './index.js',
      },
      null,
      2,
    ),
  );
}
